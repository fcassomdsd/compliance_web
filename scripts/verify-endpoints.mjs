#!/usr/bin/env node
//
// Derives the complete HTTP endpoint surface of the Express backend from the
// actual routers and their mounts in server/app.cjs, and keeps it in sync with
// docs/endpoints.md.
//
//   node scripts/verify-endpoints.mjs           # fail if docs/endpoints.md drifted
//   node scripts/verify-endpoints.mjs --write   # regenerate docs/endpoints.md
//
// The server README used to hand-list a small, stale subset of endpoints; the
// canonical list now lives in docs/endpoints.md and this script is the only
// thing that may produce it.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const serverDir = join(root, 'server');
const manifestPath = join(root, 'docs', 'endpoints.md');

const ROUTER_FILE = {
  Auth: 'auth/router.cjs',
  Findings: 'findings/router.cjs',
  Caps: 'caps/router.cjs',
  Reports: 'reports/router.cjs',
  Notifications: 'notifications/router.cjs',
  Usoap: 'usoap/router.cjs',
  NodeRedProxy: 'nodered/router.cjs',
};

// Routers that own a whole prefix instead of declaring routes of their own.
// The Node-RED proxy is mounted with router.use, so there is no per-route list
// to derive here. It is not a pass-through: which operations it forwards, and
// to which roles, is the allow-list in server/nodered/gatewayPolicy.cjs —
// documented in docs/auth/AUTH_CHUNK1_ROUTE_AUTH_MATRIX.md §5.
const PASSTHROUGH_ROUTERS = new Set(['NodeRedProxy']);

const VERBS = ['get', 'post', 'put', 'patch', 'delete'];

function read(rel) {
  return readFileSync(join(serverDir, rel), 'utf8');
}

function extractEndpoints() {
  const app = read('app.cjs');
  const endpoints = [];

  // app-level routes registered directly on the app (only /health today).
  const appRoutes = app.matchAll(/app\.(get|post|put|patch|delete)\(\s*'([^']+)'/g);
  for (const match of appRoutes) {
    endpoints.push(`${match[1].toUpperCase()} ${match[2]}`);
  }

  // app.use('/prefix', createXRouter(...)) -> resolve the router file.
  const mounts = app.matchAll(/app\.use\(\s*'([^']+)'\s*,\s*create(\w+)Router\(/g);
  for (const mount of mounts) {
    const prefix = mount[1];
    const file = ROUTER_FILE[mount[2]];
    if (!file) {
      console.error(`FAIL: unknown router creator create${mount[2]}Router in app.cjs`);
      process.exit(1);
    }
    if (PASSTHROUGH_ROUTERS.has(mount[2])) {
      endpoints.push(`ALL ${prefix}/*`);
      continue;
    }
    const routerSource = read(file);
    const routePattern = new RegExp(
      `router\\.(${VERBS.join('|')})\\(\\s*'([^']+)'`,
      'g',
    );
    for (const route of routerSource.matchAll(routePattern)) {
      const verb = route[1].toUpperCase();
      const path = route[2];
      const full = path.startsWith('/') ? `${prefix}${path === '/' ? '' : path}` : `${prefix}/${path}`;
      endpoints.push(`${verb} ${full}`);
    }
  }

  return [...new Set(endpoints)].sort();
}

function render(endpoints) {
  const lines = [
    '# Server HTTP endpoints',
    '',
    'Generated by `scripts/verify-endpoints.mjs` from the Express routers and their',
    'mounts in `server/app.cjs`. Do not edit by hand — run',
    '`node scripts/verify-endpoints.mjs --write` after changing a route and commit',
    'the result.',
    '',
    '`ALL /nodered/*` is the gateway proxy\'s mount, not a licence to call anything',
    'under it: which operations it forwards, and the roles each one needs, is the',
    'allow-list in `server/nodered/gatewayPolicy.cjs` — tabulated in',
    '[`auth/AUTH_CHUNK1_ROUTE_AUTH_MATRIX.md`](auth/AUTH_CHUNK1_ROUTE_AUTH_MATRIX.md) §5.',
    '',
    '| Method | Path |',
    '|---|---|',
    ...endpoints.map((e) => {
      const [method, path] = e.split(' ');
      return `| ${method} | \`${path}\` |`;
    }),
    '',
  ];
  return lines.join('\n');
}

const endpoints = extractEndpoints();

if (process.argv.includes('--write')) {
  writeFileSync(manifestPath, render(endpoints));
  console.log(`Wrote ${endpoints.length} endpoints to docs/endpoints.md`);
  process.exit(0);
}

const onDisk = readFileSync(manifestPath, 'utf8');
const expected = render(endpoints);

if (onDisk !== expected) {
  console.error(`FAIL: docs/endpoints.md does not match the routers (${endpoints.length} endpoints).`);
  console.error('Run `node scripts/verify-endpoints.mjs --write` to regenerate it.');
  process.exit(1);
}

console.log(`OK: docs/endpoints.md matches the routers — ${endpoints.length} endpoints`);
